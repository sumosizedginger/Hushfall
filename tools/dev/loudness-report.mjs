// THE LOUDNESS REPORT (PT-071, R22): reads the measurements of `npm run audio-qa` (validation/audio.json: every sound rendered ALONE, offline) and says where the sounds
// sit against each other, so the owner's listening pass starts with the sounds most likely to be wrong. Node only; it changes no gain and judges nothing by ear:
// a number can find an outlier, only ears can say whether it is a mistake.
//   node tools/dev/loudness-report.mjs [--write]      (--write makes design/AUDIO_LOUDNESS.md)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');

/** the family of a sound, by its id (first match wins). A new sound that matches nothing is "other" and tests/loudness.test.js fails until it is placed. */
export const FAMILIES = [
  ['cues of the score and the air',/^(heartbeat|hive_beat|radio|creak|tremor_rumble|alarm_bell)$/],
  ['chimes', /^chime_/],
  ['weapon fire', /(^|_)(fire|boom)$|^(pump|harpoon_cycle|arc_bolt|arc_charge|charge_full|saw_(start|rev|stop|loop|restart)|grav_(grab|drop|throw|punt|catch)|shot_whiz|shot_reflect)$/],
  ['melee and guard', /^(swing|swing_heavy|fist_charge|melee_hit|melee_hit_heavy|parry|guard_up|block|guard_break|saw_(hit|kick|stall)|shove_impact|head_tick)$/],
  ['the lamp and the loads', /^(lamp_|load_click|ignite_hiss|chill_crack|quench_hiss)/],
  ['pickups, the player and the interface', /^(pickup_|ui_click|level_complete|weapon_switch|dry_click|player_die)/],
  ['hits and impacts',/^(impact|hurt|burn_start|pin_thunk|shot_impact|enemy_hit|armor_ping|shield_ping|ward_ping|phys_hit|phys_break|spike_strike|pulse_hit|sweep_hit|graft_hit|seal_shatter|strike|node_sever)$/],
  ['bosses, elites and set pieces', /^(warden_|bell_(strike|slam|crush|fall|last|charge)|pulse_back|tone_pulse|sweep_tell|gate_chord|anchor_die|spike_warn|seal_die|resonator_ring|resonant_ring|reed_die|subcantor_|hivecantor_|rootbell_|grandcantor_|gatewarden_|mother_|weeping_|bulwark_|cantor_call|horn_blast)/],
  ['creature calls', /_(alert|draw|die|chirp|spit|screech|lunge|note|roar|call|hum|windup|channel|tell|swell|birth|hatch|lob|land|open|crush|burst)$|^(gaunt_|gill_|toll_|bell_alert|wheeze|revive|mender_|marksman_|snipe_|enemy_die|folk_|innocent_)/],
  ['the place', /^(step_|splash|spore_|lift_|door_|gate_|switch_|secret|load_(creak|crash)|vent_launch|air_land|void_fall|air_return|vacuum_rush|mirror_turn|receiver_|vat_)/],
];

export function familyOf(id) { for (const [name, re] of FAMILIES) if (re.test(id)) return name; return 'other'; }

const db = (x) => (x > 0 ? 20 * Math.log10(x) : -120);
const round1 = (x) => Math.round(x * 10) / 10;
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s.length ? (s.length % 2 ? s[s.length >> 1] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : 0; };

/** the report as data: per family the median loudest-window level and the sounds far from it, plus the extremes of the whole set */
export function analyse(audio, { outlierDb = 9 } = {}) {
  const sounds = audio.sfx.map((s) => ({ id: s.id, family: familyOf(s.id), lw: db(s.loudestWindowRms), peak: db(s.peak), peakLin: s.peak, rms: db(s.rms), seconds: s.seconds }));
  const families = {};
  for (const s of sounds) (families[s.family] ??= []).push(s);
  const out = [];
  for (const [name, list] of Object.entries(families)) {
    const med = median(list.map((s) => s.lw));
    out.push({ name, n: list.length, median: med, min: Math.min(...list.map((s) => s.lw)), max: Math.max(...list.map((s) => s.lw)),
      far: list.map((s) => ({ ...s, off: s.lw - med })).filter((s) => Math.abs(s.off) >= outlierDb).sort((a, b) => b.off - a.off) });
  }
  const all = sounds.map((s) => s.lw), med = median(all);
  const music = Object.fromEntries(Object.entries(audio.music ?? {}).map(([k, m]) => [k, { lw: db(m.loudestWindowRms), peak: db(m.peak), rms: db(m.rms) }]));
  return {
    sounds, families: out.sort((a, b) => b.median - a.median), median: med, loudest: [...sounds].sort((a, b) => b.lw - a.lw).slice(0, 8), quietest: [...sounds].sort((a, b) => a.lw - b.lw).slice(0, 8),
    nearClip: sounds.filter((s) => s.peakLin >= 0.9).sort((a, b) => b.peakLin - a.peakLin), music,
  };
}

const f = (x) => x.toFixed(1).replace('-', '−');

export function render(a, audio) {
  const L = [];
  L.push('# Audio loudness report (R22, generated by `node tools/dev/loudness-report.mjs --write`)');
  L.push('');
  L.push(`Read from \`validation/audio.json\` (${audio.sfx.length} sounds, ${Object.keys(audio.music ?? {}).length} music renders, measured ${audio.when} at commit ${String(audio.commit).slice(0, 8)}). **Every number here is a sound rendered ALONE, offline.** Nothing in this file says how loud the game is when a gun, a creature and the score play together through the master chain; that is a LISTENING question and belongs to the owner. This report only finds the sounds most likely to stand out, so the listening pass can start with them. No gain was changed because of it.`);
  L.push('');
  L.push('Levels are dB full scale: the loudest 100 ms window of the sound (its "punch"; what an ear weighs a short sound by) and its sample peak. A 6 dB difference is about twice as loud. A family is a group a player hears as one kind of thing (`FAMILIES` in the tool).');
  L.push('');
  L.push(`The median sound's loudest window is ${f(a.median)} dBFS; the sounds span ${f(a.quietest[0].lw)} to ${f(a.loudest[0].lw)} dBFS (${f(a.loudest[0].lw - a.quietest[0].lw)} dB).`);
  L.push('');
  L.push('## Families');
  L.push('');
  L.push('| family | sounds | median | quietest | loudest |');
  L.push('|---|---|---|---|---|');
  for (const x of a.families) L.push(`| ${x.name} | ${x.n} | ${f(x.median)} | ${f(x.min)} | ${f(x.max)} |`);
  L.push('');
  L.push('## Listen to these first');
  L.push('');
  L.push('Sounds 9 dB or more away from the median of their own family (louder first). Many are meant to be: a boss death should out-shout a footstep. The question for the ear is whether each is the right distance from the others of its kind.');
  L.push('');
  let any = false;
  for (const x of a.families) for (const s of x.far) { any = true; L.push(`- \`${s.id}\` (${x.name}): ${f(s.lw)} dBFS, ${s.off > 0 ? '+' : '−'}${f(Math.abs(s.off))} dB against the family median`); }
  if (!any) L.push('- none');
  L.push('');
  L.push('## The ends of the whole set');
  L.push('');
  L.push('Loudest windows: ' + a.loudest.map((s) => `\`${s.id}\` ${f(s.lw)}`).join(', ') + '.');
  L.push('');
  L.push('Quietest windows: ' + a.quietest.map((s) => `\`${s.id}\` ${f(s.lw)}`).join(', ') + '.');
  L.push('');
  L.push(a.nearClip.length ? 'Peaks at or above 0.9 of full scale (nothing is above 0.98: the QA run fails on clipping): ' + a.nearClip.map((s) => `\`${s.id}\` ${s.peakLin.toFixed(2)}`).join(', ') + '.' : 'No sound peaks at 0.9 of full scale or more.');
  L.push('');
  L.push('## The score against the effects');
  L.push('');
  for (const [k, m] of Object.entries(a.music)) L.push(`- ${k} music: loudest window ${f(m.lw)} dBFS, ${f(m.lw - a.median)} dB against the median effect (peak ${f(m.peak)}).`);
  L.push('');
  L.push('The game mixes the score under the effects by its own bus gains; the offline render of the score alone cannot say whether it is too quiet or too loud in play. Listen to a fight on a map with the score running.');
  L.push('');
  L.push('## How to use this');
  L.push('');
  L.push('1. Play two or three maps with headphones and with the speakers you expect players to have, once with music and once with the effect volume alone. Note, per sound, "too loud", "too quiet" or "fine" against this list (the Record of the owner\'s listening pass can be a plain list of ids).');
  L.push('2. A gain change is a change to a recipe in `src/audio/synth.js` (or its bus level in `src/audio/engine.js`) and a new `npm run audio-qa`. The audio code is one of the source sets every map\'s evidence depends on, so the change goes before the single evidence regeneration (R26).');
  L.push('3. `tests/loudness.test.js` holds the bounds that must always be true (no clipping, nothing inaudible, every sound in a family); it does not hold the balance, which only ears can.');
  return L.join('\n') + '\n';
}

if (process.argv[1] && process.argv[1].split(String.fromCharCode(92)).join('/').endsWith('loudness-report.mjs')) {
  const audio = JSON.parse(fs.readFileSync(path.join(ROOT, 'validation/audio.json'), 'utf8')), a = analyse(audio), text = render(a, audio);
  if (process.argv.includes('--write')) { fs.writeFileSync(path.join(ROOT, 'design/AUDIO_LOUDNESS.md'), text); console.log('wrote design/AUDIO_LOUDNESS.md'); }
  else console.log(text);
  const other = a.sounds.filter((s) => s.family === 'other'); if (other.length) console.log('NOT IN A FAMILY: ' + other.map((s) => s.id).join(', '));
}

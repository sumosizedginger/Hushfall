// THE FACTS A STORE PAGE MAY STATE (PT-071, R23): counted from the game's own data, so the copy cannot promise what the game does not hold. Node only, read-only.
//   node tools/dev/store-facts.mjs [--write]      --write makes design/store/FACTS.md
import fs from 'node:fs';
import path from 'node:path';
import { WEAPONS, WEAPON_ORDER, MELEE_ORDER, ENEMIES, AMMO_LOADS, MODS, LOOKS, DIFFICULTY } from '../../src/engine/defs.js';
import { loadMapFile, loadRouteFile, runRoute } from '../../src/engine/harness.js';

const root = path.resolve(import.meta.dirname, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'CAMPAIGN_MANIFEST.json'), 'utf8'));
const maps = manifest.maps, byKind = (k) => maps.filter((m) => m.kind === k);
const dirBytes = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? dirBytes(path.join(d, e.name)) : fs.statSync(path.join(d, e.name)).size), 0) : 0);

let creatures = 0, nodes = 0, peaceful = 0;
for (const [k, d] of Object.entries(ENEMIES)) { if (d.peaceful) peaceful++; else if (d.node) nodes++; else creatures++; }
const bosses = Object.entries(ENEMIES).filter(([, d]) => d.boss).map(([k]) => ENEMIES[k].name);
const guns = WEAPON_ORDER.filter((w) => !MELEE_ORDER.includes(w)), melee = MELEE_ORDER;
let totalMessages = 0, totalWords = 0; for (const m of maps) { const j = JSON.parse(fs.readFileSync(path.join(root, 'maps', m.id + '.json'), 'utf8')); for (const x of j.messages ?? []) { totalMessages++; totalWords += (x.text.match(/\S+/g) || []).length; } }
// how long a route takes the bot (a person takes several times as long): the sum over main routes, Normal
let botSeconds = 0, counted = 0;
if (process.argv.includes('--time')) for (const m of byKind('main')) { const rf = path.join(root, 'routes', m.id + '.main.route.json'); if (!fs.existsSync(rf)) continue; const r = runRoute(loadMapFile(path.join(root, 'maps', m.id + '.json')), loadRouteFile(rf), { seed: 1, difficulty: 'normal' }); botSeconds += r.ticks / 60; counted++; }

const facts = {
  maps: maps.length, mainMaps: byKind('main').length, secretMaps: byKind('secret').length, campaigns: 2,
  campaign1: maps.filter((m) => m.campaign === 1).length, campaign2: maps.filter((m) => m.campaign === 2).length,
  guns: guns.length, melee: melee.length, weaponsTotal: guns.length + melee.length, loads: Object.keys(AMMO_LOADS).length, mods: Object.keys(MODS).length,
  creatures, nodes, peaceful, bosses, looks: Object.keys(LOOKS).length, difficulties: Object.values(DIFFICULTY).map((d) => d.name),
  messages: totalMessages, words: totalWords,
  distMB: +(dirBytes(path.join(root, 'dist')) / 1048576).toFixed(1), bakedMB: +(dirBytes(path.join(root, 'assets/baked')) / 1048576).toFixed(1),
  ...(counted ? { botMinutesMain: +(botSeconds / 60).toFixed(0), routesCounted: counted } : {}),
};
console.log(JSON.stringify(facts, null, 1));
if (process.argv.includes('--write')) {
  const md = `# Facts a store page may state (generated by tools/dev/store-facts.mjs; counted from the game's data)\n\n${Object.entries(facts).map(([k, v]) => `- **${k}**: ${Array.isArray(v) ? v.join(', ') : v}`).join('\n')}\n\nA person takes several times what the bot takes. The numbers of weapons, creatures and maps are counts of what the game holds; "bosses" are the creatures marked boss in defs.js. Nothing here is a claim about quality.\n`;
  fs.mkdirSync(path.join(root, 'design/store'), { recursive: true }); fs.writeFileSync(path.join(root, 'design/store/FACTS.md'), md); console.log('wrote design/store/FACTS.md');
}

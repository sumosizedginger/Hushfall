// A8 part 2 (2026-11-14): choose one accent lamp of the other temperature per map whose look still has no warm-against-cool pair, and write
// src/render/accents.js. The lamp is drawn by levelmesh.js only (never in the sim's map, so routes do not change).
//   node tools/dev/accent-lamps.mjs <looks.json>       (looks.json = the look table of the last full hero shoot, e.g. D:/Doom_release/awe/looks-a8d.json)
// A look needs a pair when it is under 50% coloured, or under 10% warm, or under 10% cool (frame-score's colour rule). The tint: no cool -> blue,
// no warm -> amber, both present but too little colour -> the lesser of the two. The spot: a floor cell 5 to 18 m ahead of the map's hero view
// (maps-src/hero-views.json), a little to one side so it is in frame but not on the subject, seen from the view without a wall between, not on a
// prop, not more than 3 m above or below the view's floor. Under a roof up to 4.5 m it hangs (`lamp`), elsewhere it stands on a post (`lamppost`) against a wall, because a
// post is drawn only and must not stand where the player walks; a map with no such spot gets none (it needs a real lamp in its source).
import fs from 'node:fs';
import path from 'node:path';
import { loadMapFile } from '../../src/engine/harness.js';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const looks = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const views = JSON.parse(fs.readFileSync(path.join(ROOT, 'maps-src', 'hero-views.json'), 'utf8'));
const need = Object.fromEntries(looks.filter((r) => r.needs).map((r) => [r.look, r]));
// a map with a real accent lamp in its source (maps-src/accent-lamps.json, tools/dev/source-lamps.mjs) gets no drawn one as well
const realFile = path.join(ROOT, 'maps-src', 'accent-lamps.json'),
  real = fs.existsSync(realFile) ? JSON.parse(fs.readFileSync(realFile, 'utf8')) : {};
const tintOf = (r) => (r.cool < 10 ? 'blue' : r.warm < 10 ? 'amber' : r.cool <= r.warm ? 'blue' : 'amber');
const ROOFED = new Set(['floor', 'door', 'secret']);
const out = {},
  miss = [];

for (const id of Object.keys(views).sort()) {
  const file = path.join(ROOT, 'maps', id + '.json');
  if (!fs.existsSync(file)) continue;
  const map = loadMapFile(file),
    look = need[map.atmosphere?.look ?? 'harbour'];
  if (!look || real[id]) continue;
  const v = { ...views[id], x: views[id].x * map.cell, z: views[id].z * map.cell }, // (hero views are kept in cells; the shoot multiplies by the cell)
    S = map.cell,
    fx = -Math.sin(v.yaw),
    fz = -Math.cos(v.yaw),
    vfy = map.floor(Math.floor(v.x / S), Math.floor(v.z / S));
  const taken = new Set(map.props.map((p) => Math.floor(p.at[0]) + ',' + Math.floor(p.at[1])));
  const open = (cx, cz) => {
    const k = map.kind(cx, cz);
    return k !== 'wall' && k !== undefined;
  };
  const seen = (x, z) => {
    const d = Math.hypot(x - v.x, z - v.z);
    for (let t = 0.5; t < d; t += 0.5) {
      const px = v.x + ((x - v.x) * t) / d,
        pz = v.z + ((z - v.z) * t) / d;
      if (!open(Math.floor(px / S), Math.floor(pz / S))) return false;
    }
    return true;
  };
  // a post is drawn only, so the player could walk through it: first look for a cell with a wall beside it (the post stands against the wall),
  // and only then anywhere
  const byWall = (cx, cz) => [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dz]) => map.kind(cx + dx, cz + dz) === 'wall');
  let pick = null;
  search: for (const wallOnly of [true])
  for (const d of [8, 7, 9, 10, 6, 11, 12, 5, 13, 14, 15, 16, 18])
    for (const s of [3, -3, 4.5, -4.5, 2, -2, 6, -6, 8, -8, 10, -10]) {
      const x = v.x + fx * d - fz * s,
        z = v.z + fz * d + fx * s,
        cx = Math.floor(x / S),
        cz = Math.floor(z / S),
        k = map.kind(cx, cz);
      if (cx < 0 || cz < 0 || cx >= map.w || cz >= map.h) continue;
      if (k !== 'floor' && k !== 'outdoor') continue;
      if (taken.has(cx + ',' + cz) || Math.abs(map.floor(cx, cz) - vfy) > 3) continue;
      if (!seen((cx + 0.5) * S, (cz + 0.5) * S)) continue;
      const kind = ROOFED.has(k) && map.ceilingAt(cx, cz) - map.floor(cx, cz) <= 4.5 ? 'lamp' : 'lamppost';
      if (wallOnly && kind === 'lamppost' && !byWall(cx, cz)) continue;
      pick = { at: [cx, cz], kind, tint: tintOf(look), look: look.look, d, s, wall: byWall(cx, cz) };
      break search;
    }
  if (pick) out[id] = pick;
  else miss.push(id);
}

const lines = [
  '// GENERATED by tools/dev/accent-lamps.mjs (A8 part 2, 2026-11-14) from the look table of the last full hero shoot. Do not edit by hand: rerun.',
  '// One lamp of the other temperature per map whose look had no warm-against-cool pair (blue in a warm place, amber in a cool one), a few metres',
  '// ahead of its hero view. levelmesh.js draws it and lights the walls with it; the simulation never sees it.',
  'export const ACCENTS = {',
];
for (const [id, a] of Object.entries(out))
  lines.push(`  ${id}: [{ at: [${a.at[0]}, ${a.at[1]}], kind: '${a.kind}', tint: '${a.tint}' }], // ${a.look}: ${a.d} m ahead, ${a.s} m aside${a.kind === 'lamppost' && !a.wall ? ', free-standing' : ''}`);
lines.push('};', '');
fs.writeFileSync(path.join(ROOT, 'src', 'render', 'accents.js'), lines.join('\n'));
console.log('accents', Object.keys(out).length, '; no spot found:', miss.join(' ') || 'none');
for (const [id, a] of Object.entries(out)) console.log(id.padEnd(8), a.look.padEnd(11), a.tint.padEnd(6), a.kind.padEnd(9), a.at.join(','));

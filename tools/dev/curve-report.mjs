// The campaign's difficulty, map by map (PT-083 D3). Read from the evidence verify-map wrote (validation/maps/<ID>.json): how much the perfect fighter was hurt on each difficulty, and how much ammunition it had to spare. It writes
// design/DIFFICULTY_CURVE.md and flags a map well above its neighbours, or a long stretch with nothing to fear. A bot is not a person: this finds outliers, it does not judge how hard the game is.
//   node tools/dev/curve-report.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'CAMPAIGN_MANIFEST.json'), 'utf8'));
const rows = [];
const num = (s, re) => {
  const m = String(s ?? '').match(re);
  return m ? Number(m[1]) : null;
};
for (const slot of manifest.maps.filter((m) => m.kind === 'main')) {
  const file = path.join(root, 'validation', 'maps', slot.id + '.json');
  if (!fs.existsSync(file)) continue;
  const v = JSON.parse(fs.readFileSync(file, 'utf8')),
    via = v.viability ?? v.automated?.viability ?? {},
    r = { id: slot.id, name: slot.name };
  for (const d of ['easy', 'normal', 'hard']) {
    const q = via[d] ?? {};
    r[d] = {
      // the mean over the seeds: one run's damage is chaotic (Rail Yard's first run: 182 on Normal, 36 on Hard)
      damage: q.fighter?.meanDamage ?? q.fighter?.damage ?? q.fighter?.damageTaken ?? q.damage ?? null,
      seeds: q.fighter?.completedSeeds ?? null,
      slack: q.ammo?.capacity && q.ammo?.fired ? Math.round((q.ammo.capacity / q.ammo.fired) * 10) / 10 : null,
    };
  }
  rows.push(r);
}
const flags = [];
rows.forEach((r, i) => {
  const near = rows.slice(Math.max(0, i - 3), i + 4).filter((q) => q !== r && Number.isFinite(q.normal.damage));
  if (!near.length || !Number.isFinite(r.normal.damage)) return;
  const mean = near.reduce((a, q) => a + q.normal.damage, 0) / near.length;
  if (mean > 10 && r.normal.damage > 1.5 * mean)
    flags.push(`${r.id} ${r.name}: ${r.normal.damage} damage on Normal against about ${Math.round(mean)} around it`);
});
let calm = [];
for (const r of rows) {
  if (Number.isFinite(r.normal.damage) && r.normal.damage < 10) calm.push(r);
  else {
    if (calm.length >= 3) flags.push(`a stretch with little to fear: ${calm.map((q) => q.id).join(', ')}`);
    calm = [];
  }
}
const cell = (x) => (x == null ? '-' : x);
const out = [
  '# The difficulty curve (generated by `node tools/dev/curve-report.mjs`)',
  '',
  'How much the perfect fighter was hurt on each main map, and the ammunition it had to spare (how many times over it could have fired what it fired). A bot is not a person: this finds outliers and does not say how hard the game is. Every number comes from the last `verify-map`.',
  '',
  flags.length ? '## Flagged\n\n' + flags.map((f) => '- ' + f).join('\n') + '\n' : '## Flagged\n\nNothing.\n',
  '## Every map',
  '',
  '| map | name | damage easy | damage normal | damage hard | ammo x easy | ammo x normal | ammo x hard |',
  '|---|---|---|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| ${r.id} | ${r.name} | ${cell(r.easy.damage)} | ${cell(r.normal.damage)} | ${cell(r.hard.damage)} | ${cell(r.easy.slack)} | ${cell(r.normal.slack)} | ${cell(r.hard.slack)} |`,
  ),
  '',
];
fs.writeFileSync(path.join(root, 'design', 'DIFFICULTY_CURVE.md'), out.join('\n'));
console.log(`${rows.length} maps, ${flags.length} flag(s)`);
for (const f of flags) console.log(f);
